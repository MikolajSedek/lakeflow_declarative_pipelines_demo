class TestCreateAutoCdcFlowInvocation:
    """Tests that create_auto_cdc_flow is called with the correct arguments."""

    def test_cdc_flow_is_called_once(self, registry, mock_cdc):
        """Should invoke create_auto_cdc_flow exactly once per pipeline run."""
        _PIPELINE.create_orders_scd2_table()

        assert mock_cdc.call_count == 1

    def test_cdc_flow_target_matches_streaming_table(self, registry, mock_cdc):
        """Should pass the same fully-qualified name as both the table and CDC target."""
        _PIPELINE.create_orders_scd2_table()

        assert (
            mock_cdc.call_args.kwargs["target"] == "test_catalog.test_gold_schema.fake_orders_scd2"
        )

    def test_cdc_flow_source_is_staging_table(self, registry, mock_cdc):
        """Should read from the silver staging table."""
        _PIPELINE.create_orders_scd2_table()

        assert (
            mock_cdc.call_args.kwargs["source"]
            == "test_catalog.test_silver_schema.fake_orders_staging"
        )

    def test_cdc_flow_keys_contain_id(self, registry, mock_cdc):
        """Should use 'id' as the CDC primary key."""
        _PIPELINE.create_orders_scd2_table()

        assert mock_cdc.call_args.kwargs["keys"] == ["id"]

    def test_cdc_flow_sequence_by_is_timestamp(self, registry, mock_cdc):
        """Should sequence CDC events by the 'timestamp' column."""
        _PIPELINE.create_orders_scd2_table()

        assert mock_cdc.call_args.kwargs["sequence_by"] == "timestamp"

    def test_cdc_flow_stored_as_scd_type_2(self, registry, mock_cdc):
        """Should store as SCD Type 2 to preserve full product change history."""
        _PIPELINE.create_orders_scd2_table()

        assert mock_cdc.call_args.kwargs["stored_as_scd_type"] == 2

    def test_cdc_flow_tracks_productid_history(self, registry, mock_cdc):
        """Should limit history tracking to the 'productid' column."""
        _PIPELINE.create_orders_scd2_table()

        assert mock_cdc.call_args.kwargs["track_history_column_list"] == ["productid"]

    def test_cdc_flow_ignores_null_updates(self, registry, mock_cdc):
        """Should set ignore_null_updates=True to avoid overwriting existing data with nulls."""
        _PIPELINE.create_orders_scd2_table()

        assert mock_cdc.call_args.kwargs["ignore_null_updates"] is True
