class TestCreateStreamingTableRegistration:
    """Tests that create_orders_scd2_table registers a StreamingTable correctly."""

    def test_registers_one_streaming_table(self, registry, mock_cdc):
        """Should register exactly one StreamingTable output."""
        _PIPELINE.create_orders_scd2_table()

        st_outputs = [o for o in registry.outputs if isinstance(o, StreamingTable)]
        assert len(st_outputs) == 1

    def test_streaming_table_has_correct_name(self, registry, mock_cdc):
        """Should register the streaming table with the fully-qualified target name."""
        _PIPELINE.create_orders_scd2_table()

        st = next(o for o in registry.outputs if isinstance(o, StreamingTable))
        assert st.name == "test_catalog.test_gold_schema.fake_orders_scd2"

    def test_streaming_table_has_comment(self, registry, mock_cdc):
        """Should attach a non-empty descriptive comment to the streaming table."""
        _PIPELINE.create_orders_scd2_table()

        st = next(o for o in registry.outputs if isinstance(o, StreamingTable))
        assert st.comment is not None
        assert len(st.comment) > 0

    def test_no_extra_outputs_registered(self, registry, mock_cdc):
        """Should register no outputs beyond the single SCD2 streaming table."""
        _PIPELINE.create_orders_scd2_table()

        assert len(registry.outputs) == 1

    def test_no_flows_registered_in_registry(self, registry, mock_cdc):
        """Should not register any flows — CDC flow is handled outside the registry."""
        _PIPELINE.create_orders_scd2_table()

        assert len(registry.flows) == 0


