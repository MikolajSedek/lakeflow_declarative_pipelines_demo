"""Unit tests for the SCD Type 2 pipeline (04.scd_genie_code_pipeline.py).

The pipeline is generated by Databricks Genie and uses the Databricks-specific
``create_auto_cdc_flow`` API (unavailable in open-source PySpark). Tests verify
the pipeline structure, module-level constants, and the exact arguments forwarded
to both ``create_streaming_table`` and ``create_auto_cdc_flow``.
"""

import importlib.util
from pathlib import Path
from unittest.mock import MagicMock, patch

import pyspark.pipelines as dp_mod
import pytest
from pyspark.pipelines.flow import Flow
from pyspark.pipelines.graph_element_registry import (
    GraphElementRegistry,
    graph_element_registration_context,
)
from pyspark.pipelines.output import Output, StreamingTable

# ---------------------------------------------------------------------------
# Module loader
# ---------------------------------------------------------------------------

_PIPELINE_PATH = Path(__file__).parent.parent / "04.scd_genie_code_pipeline.py"


def _load_pipeline_module():
    """Load the SCD pipeline module directly from its file path."""
    spec = importlib.util.spec_from_file_location("scd_pipeline", _PIPELINE_PATH)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


_PIPELINE = _load_pipeline_module()

# ---------------------------------------------------------------------------
# Test helpers
# ---------------------------------------------------------------------------


class MockGraphElementRegistry(GraphElementRegistry):
    """Collects all outputs and flows registered during a pipeline definition."""

    def __init__(self):
        self.outputs: list[Output] = []
        self.flows: list[Flow] = []

    def register_output(self, output: Output) -> None:
        """Record an output in the mock registry."""
        self.outputs.append(output)

    def register_flow(self, flow: Flow) -> None:
        """Record a flow in the mock registry."""
        self.flows.append(flow)

    def register_sql(self, sql_text: str, file_path: Path) -> None:
        """No-op: SQL registration is not needed for Python-only tests."""


@pytest.fixture
def registry():
    """Provide a fresh MockGraphElementRegistry inside a registration context."""
    reg = MockGraphElementRegistry()
    with graph_element_registration_context(reg):
        yield reg


@pytest.fixture
def mock_cdc():
    """Patch create_auto_cdc_flow (Databricks-only) onto the pyspark.pipelines module."""
    with patch.object(dp_mod, "create_auto_cdc_flow", MagicMock(), create=True) as m:
        yield m


